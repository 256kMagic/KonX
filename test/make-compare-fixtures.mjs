// Regenerates deterministic synthetic pcapng fixtures using the project's
// byte-accurate test builders. No real host or network traffic is used.
import fs from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import * as P from './lib/packets.mjs';
import { writePcapng } from '../src/renderer/js/capture/pcapfile.mjs';

export function demoPackets(failing = false, options = {}) {
  const client = options.client || '192.0.2.10', server = options.server || '198.51.100.20', resolver = '192.0.2.53';
  const port = options.port || (failing ? 54042 : 53001), base = options.base ?? (failing ? 1800000000 : 1700000000);
  const m1 = '02:00:00:00:00:01', m2 = '02:00:00:00:00:02', packets = [];
  const add = (time, data) => packets.push({ ts: base + time, data, caplen: data.length, len: data.length, linktype: 1 });
  const tcp = (time, reverse, fields, payload = '') => add(time, P.frame.tcp(m1, m2, reverse ? server : client, reverse ? client : server,
    { sport: reverse ? 80 : port, dport: reverse ? port : 80, ...fields }, P.str(payload)));
  add(0, P.frame.udp(m1, m2, client, resolver, { sport: port + 1, dport: 53 }, P.dns({ id: 71, name: 'app.example.test' })));
  add(failing ? .2 : .005, P.frame.udp(m2, m1, resolver, client, { sport: 53, dport: port + 1 }, P.dns({ id: 71, name: 'app.example.test', response: true,
    rcode: failing ? 2 : 0, answers: failing ? [] : [{ type: 'A', data: server }] })));
  const setup = failing ? .25 : .01, requestAt = failing ? .4 : .12, responseAt = failing ? 1.3 : .16;
  tcp(.1, false, { seq: 100, flags: 'S' });
  tcp(.1 + setup, true, { seq: 500, ack: 101, flags: 'SA' });
  tcp(.101 + setup, false, { seq: 101, ack: 501, flags: 'A' });
  const request = 'GET /status HTTP/1.1\r\nHost: app.example.test\r\n\r\n', split = 17;
  tcp(requestAt, false, { seq: 101, ack: 501, flags: 'PA' }, request.slice(0, split));
  tcp(requestAt + .001, false, { seq: 101 + split, ack: 501, flags: 'PA' }, request.slice(split));
  if (failing) tcp(requestAt + .005, false, { seq: 101 + split, ack: 501, flags: 'PA' }, request.slice(split));
  const body = failing ? 'temporarily unavailable' : 'ok', response = `HTTP/1.1 ${failing ? '503 Service Unavailable' : '200 OK'}\r\nContent-Length: ${body.length}\r\nContent-Type: text/plain\r\n\r\n${body}`;
  tcp(responseAt, true, { seq: 501, ack: 101 + request.length, flags: 'PA' }, response.slice(0, 23));
  tcp(responseAt + .001, true, { seq: 524, ack: 101 + request.length, flags: 'PA' }, response.slice(23));
  tcp(responseAt + .05, true, { seq: 501 + response.length, ack: 101 + request.length, flags: failing ? 'RA' : 'FA' });
  if (!failing) tcp(responseAt + .051, false, { seq: 101 + request.length, ack: 502 + response.length, flags: 'FA' });
  return packets;
}

export async function writeDemoFixtures() {
  const before = writePcapng(demoPackets(false)), after = writePcapng(demoPackets(true));
  const code = `// Synthetic documentation-address captures; generated by make-compare-fixtures.mjs.\n` +
    `const before = '${Buffer.from(before).toString('base64')}';\nconst after = '${Buffer.from(after).toString('base64')}';\n` +
    `const bytes = text => Uint8Array.from(atob(text), char => char.charCodeAt(0));\n` +
    `export function createComparisonDemo() { return { before: { name: 'working-demo.pcapng', bytes: bytes(before) }, after: { name: 'failing-demo.pcapng', bytes: bytes(after) } }; }\n`;
  await fs.writeFile(new URL('../src/renderer/js/capture/sample-compare.mjs', import.meta.url), code);
  return { beforeBytes: before.length, afterBytes: after.length };
}
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) console.log(await writeDemoFixtures());
